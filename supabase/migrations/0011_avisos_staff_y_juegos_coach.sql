create table angels.staff_push_subscriptions (
  id          bigint generated by default as identity primary key,
  email       text not null,
  endpoint    text not null unique,
  p256dh      text not null,
  auth        text not null,
  user_agent  text,
  created_at  timestamptz not null default now(),
  last_ok_at  timestamptz,
  failures    int not null default 0,
  constraint staff_push_endpoint_https check (endpoint like 'https://%' and length(endpoint) <= 1000)
);

create table angels.staff_alert_log (
  key        text primary key,
  kind       text not null,
  body       text not null,
  sent_at    timestamptz not null default now(),
  delivered  int not null default 0
);

alter table angels.staff_push_subscriptions enable row level security;
alter table angels.staff_alert_log          enable row level security;
create policy staff_push_subscriptions_staff on angels.staff_push_subscriptions for select to authenticated using ((select angels.is_staff()));
create policy staff_alert_log_staff          on angels.staff_alert_log          for select to authenticated using ((select angels.is_staff()));
revoke all on angels.staff_push_subscriptions, angels.staff_alert_log from anon, authenticated;
grant select on angels.staff_push_subscriptions, angels.staff_alert_log to authenticated;
grant all on angels.staff_push_subscriptions, angels.staff_alert_log to service_role;
grant usage, select on all sequences in schema angels to authenticated, service_role;

-- El staff guarda la suscripcion de su telefono. Maximo 4 telefonos.
create or replace function angels.staff_save_push(p_endpoint text, p_p256dh text, p_auth text, p_ua text)
 returns jsonb
 language plpgsql security definer
 set search_path to 'angels', 'pg_temp'
as $function$
declare v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
begin
  if not angels.is_staff() or v_email = '' then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  if p_endpoint is null or p_endpoint not like 'https://%' or length(p_endpoint) > 1000 then
    raise exception 'Suscripcion no valida'; end if;
  if p_p256dh is null or length(p_p256dh) > 200 or p_auth is null or length(p_auth) > 100 then
    raise exception 'Suscripcion no valida'; end if;
  insert into angels.staff_push_subscriptions (email, endpoint, p256dh, auth, user_agent)
  values (v_email, p_endpoint, p_p256dh, p_auth, left(p_ua, 200))
  on conflict (endpoint) do update
    set email = excluded.email, p256dh = excluded.p256dh, auth = excluded.auth,
        user_agent = excluded.user_agent, failures = 0;
  return jsonb_build_object('ok', true);
end;
$function$;

-- Que avisos le tocan al staff ahora mismo. Solo la llama angels-push.
create or replace function angels.staff_alerts_due()
 returns table(key text, kind text, body text)
 language plpgsql stable security definer
 set search_path to 'angels', 'pg_temp'
as $function$
declare
  v_now   timestamp := now() at time zone 'America/Puerto_Rico';
  v_today date := (now() at time zone 'America/Puerto_Rico')::date;
begin
  if not exists (select 1 from angels.staff_push_subscriptions) then return; end if;

  -- Resumen de la sesion: misma ventana que el aviso 1 de los jugadores.
  return query
  with ses as (
    select t.team, d.dia
    from (select distinct pl.team from angels.players pl where pl.status = 'activo') t
    cross join (values (v_today), (v_today - 1)) as d(dia)
    where angels.team_has_session(t.team, d.dia)
      and v_now >= angels.session_end_at(t.team, d.dia) + interval '30 minutes'
      and v_now <  angels.session_end_at(t.team, d.dia) + interval '3 hours'
  ), est as (
    select s.team, s.dia, p.number,
           exists (select 1 from angels.entries e where e.player_id = p.id and e.date = s.dia) as hecho,
           exists (select 1 from angels.availability a where a.player_id = p.id and a.date = s.dia and a.status in ('ninguno','lesionado')) as excusado
    from ses s join angels.players p on p.team = s.team and p.status = 'activo'
  )
  select 'resumen:' || e.team || ':' || e.dia,
         'resumen'::text,
         'Angels: ' || count(*) filter (where e.hecho) || ' de ' || count(*) filter (where not e.excusado) ||
         ' hicieron el check-in.' ||
         coalesce(' Faltan ' || string_agg('#' || e.number, ', ' order by nullif(regexp_replace(e.number, '\D', '', 'g'), '')::int)
                    filter (where not e.hecho and not e.excusado) || '.', ' No falta nadie.')
  from est e
  where not exists (select 1 from angels.staff_alert_log l where l.key = 'resumen:' || e.team || ':' || e.dia)
  group by e.team, e.dia;

  -- Seguimiento: dia siguiente de 9pm a 11:59pm, despues del ultimo aviso.
  if v_now::time >= time '21:00' then
    return query
    select 'seguimiento:' || p.team || ':' || (v_today - 1),
           'seguimiento'::text,
           'Angels: siguen sin check-in de ayer después del último aviso: ' ||
           string_agg('#' || p.number, ', ' order by nullif(regexp_replace(p.number, '\D', '', 'g'), '')::int) || '.'
    from angels.players p
    where p.status = 'activo'
      and angels.team_has_session(p.team, v_today - 1)
      and not exists (select 1 from angels.entries e where e.player_id = p.id and e.date = v_today - 1)
      and not exists (select 1 from angels.availability a where a.player_id = p.id and a.date = v_today - 1 and a.status in ('ninguno','lesionado'))
      and not exists (select 1 from angels.staff_alert_log l where l.key = 'seguimiento:' || p.team || ':' || (v_today - 1))
    group by p.team;
  end if;

  -- Salud: de 7am a 10pm. Lo reportado en las ultimas 36 horas que no se
  -- ha avisado. Sin nombre, sin numero, sin detalle.
  if v_now::time >= time '07:00' and v_now::time < time '22:00' then
    return query
    select 'salud:entry:' || e.id, 'salud'::text,
           'Angels: un jugador reportó algo que debes revisar. Ábrelo en la app.'::text
    from angels.entries e join angels.players p on p.id = e.player_id
    where e.created_at > now() - interval '36 hours'
      and (coalesce(e.pain_concern, 0) >= 2 or coalesce(e.illness, 0) >= 2)
      and not exists (select 1 from angels.staff_alert_log l where l.key = 'salud:entry:' || e.id);

    return query
    select 'salud:avail:' || a.id, 'salud'::text,
           'Angels: un jugador se marcó lesionado. Ábrelo en la app.'::text
    from angels.availability a join angels.players p on p.id = a.player_id
    where a.created_at > now() - interval '36 hours'
      and a.status = 'lesionado'
      and not exists (select 1 from angels.staff_alert_log l where l.key = 'salud:avail:' || a.id);
  end if;
end;
$function$;

