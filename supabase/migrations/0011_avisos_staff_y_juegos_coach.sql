create table angels.staff_game_records (
  game           text        primary key,
  best_score     integer     not null default 0,
  best_level     integer,
  best_meta      jsonb       not null default '{}'::jsonb,
  best_at        timestamptz,
  plays          integer     not null default 0,
  last_played_at timestamptz,
  constraint staff_game_records_game_chk check (game = any (array['keepup','longspike'])),
  constraint staff_game_records_score_chk check (best_score >= 0)
);
alter table angels.staff_game_records enable row level security;
create policy staff_game_records_staff on angels.staff_game_records for select to authenticated
  using ((select angels.is_staff()));
revoke all on angels.staff_game_records from anon, authenticated;
grant select on angels.staff_game_records to authenticated;
grant all on angels.staff_game_records to service_role;

-- Misma validacion que la partida de un jugador.
create or replace function angels.staff_game_submit(p_game text, p_score integer, p_meta jsonb)
returns jsonb
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_prev    angels.staff_game_records%rowtype;
  v_secs    numeric;
  v_level   integer;
  v_touches integer;
  v_record  boolean := false;
  v_best    integer;
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  if p_game is null or p_game <> all (array['keepup','longspike']) then
    raise exception 'Juego no valido';
  end if;
  if p_score is null or p_score < 0 then
    raise exception 'Puntuacion no valida';
  end if;
  v_secs := coalesce((p_meta->>'secs')::numeric, 0);
  if v_secs < 1 or v_secs > 7200 then
    raise exception 'Partida no valida';
  end if;
  if p_game = 'keepup' then
    v_level   := coalesce((p_meta->>'level')::integer, 1);
    v_touches := coalesce((p_meta->>'touches')::integer, 0);
    if v_level < 1 or v_touches < 0
       or v_touches > v_secs * 4 + 5
       or v_level > 1 + v_secs / 6
       or p_score > v_secs * 150 + 600 then
      raise exception 'Partida no valida';
    end if;
  else
    v_level := null;
    if p_score > 20000 or p_score > v_secs * 350 + 300 then
      raise exception 'Partida no valida';
    end if;
  end if;

  select * into v_prev from angels.staff_game_records where game = p_game;
  if not found then
    insert into angels.staff_game_records (game, best_score, best_level, best_meta, best_at, plays, last_played_at)
    values (p_game, p_score, v_level, coalesce(p_meta, '{}'::jsonb), now(), 1, now());
    v_record := p_score > 0;
    v_best := p_score;
  else
    v_record := p_score > v_prev.best_score;
    update angels.staff_game_records
       set plays = plays + 1,
           last_played_at = now(),
           best_score = case when v_record then p_score else best_score end,
           best_level = case when v_record then v_level else best_level end,
           best_meta  = case when v_record then coalesce(p_meta, '{}'::jsonb) else best_meta end,
           best_at    = case when v_record then now() else best_at end
     where game = p_game;
    v_best := greatest(p_score, v_prev.best_score);
  end if;
  return jsonb_build_object('best', v_best, 'record', v_record);
end;
$$;

-- Top del club para un juego, con el coach incluido. p_me_coach marca la
-- fila del coach como "me" (la usa el staff_game_board).
create or replace function angels.game_board_club(p_game text, p_player_id text, p_me_coach boolean)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_top jsonb;
  v_me  jsonb;
begin
  with base as (
    select r.player_id, r.best_score, r.best_level, p.team, p.number,
           split_part(trim(p.name), ' ', 1) as first_name, false as coach
      from angels.game_records r
      join angels.players p on p.id = r.player_id
     where r.game = p_game and r.best_score > 0 and p.status = 'activo'
    union all
    select null, s.best_score, s.best_level, 'Staff', '', 'Coach', true
      from angels.staff_game_records s
     where s.game = p_game and s.best_score > 0
  ), ranked as (
    select b.*, rank() over (order by b.best_score desc) as pos from base b
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'pos', pos, 'number', number, 'name', first_name, 'team', team,
           'score', best_score, 'level', best_level, 'coach', coach,
           'me', case when p_me_coach then coach else coalesce(player_id = p_player_id, false) end
         ) order by pos, first_name) filter (where pos <= 10), '[]'::jsonb),
         (select jsonb_build_object('pos', pos, 'score', best_score) from ranked
           where (p_me_coach and coach) or (not p_me_coach and player_id = p_player_id) limit 1)
    into v_top, v_me
    from ranked;
  return jsonb_build_object('top', coalesce(v_top, '[]'::jsonb), 'me', v_me);
end;
$$;

-- El top de los jugadores: igual que antes en 'team'; en 'club' incluye al coach.
create or replace function angels.player_game_board(p_token text, p_game text, p_scope text)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_player angels.players%rowtype;
  v_top    jsonb;
  v_me     jsonb;
  v_club   jsonb;
begin
  if p_token is null or length(p_token) < 32 then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  select * into v_player from angels.players where access_token = p_token;
  if not found then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  if p_game is null or p_game <> all (array['keepup','longspike']) then
    raise exception 'Juego no valido';
  end if;

  if coalesce(p_scope, 'team') = 'club' then
    v_club := angels.game_board_club(p_game, v_player.id, false);
    return v_club || jsonb_build_object('team', v_player.team);
  end if;

  with ranked as (
    select r.player_id, r.best_score, r.best_level, p.team, p.number,
           split_part(trim(p.name), ' ', 1) as first_name,
           rank() over (order by r.best_score desc) as pos
      from angels.game_records r
      join angels.players p on p.id = r.player_id
     where r.game = p_game
       and r.best_score > 0
       and p.status = 'activo'
       and p.team = v_player.team
  )
  select coalesce(jsonb_agg(jsonb_build_object(
           'pos', pos, 'number', number, 'name', first_name, 'team', team,
           'score', best_score, 'level', best_level, 'me', player_id = v_player.id
         ) order by pos, first_name) filter (where pos <= 10), '[]'::jsonb),
         (select jsonb_build_object('pos', pos, 'score', best_score) from ranked where player_id = v_player.id)
    into v_top, v_me
    from ranked;

  return jsonb_build_object('top', coalesce(v_top, '[]'::jsonb), 'me', v_me, 'team', v_player.team);
end;
$$;

-- Top que ve el coach desde los juegos: siempre el del club.
create or replace function angels.staff_game_board(p_game text)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  if p_game is null or p_game <> all (array['keepup','longspike']) then
    raise exception 'Juego no valido';
  end if;
  return angels.game_board_club(p_game, null, true) || jsonb_build_object('team', 'Club');
end;
$$;

