-- =====================================================================
-- ANGELS (derivado de STATION v2.5.1) - 0004 NOTIFICACIONES PUSH Y TAREAS PROGRAMADAS
--  * push_subscriptions: el telefono de cada jugador que activo los
--    recordatorios (Web Push estandar: endpoint + llaves del navegador).
--  * reminder_log: que recordatorio se mando a quien, para no repetir.
--  * reminders_due(): quien debe recibir aviso ahora mismo.
--      Intento 1: 30 min despues de terminar la practica (o a las 8pm en
--      dia de torneo), solo a quien no ha hecho el check-in de ese dia.
--      Intento 2: al dia siguiente a las 6pm, ultimo aviso.
--    Maximo 2 avisos por sesion. Los dias "no entreno"/"lesionado" no avisan.
--  * Las llaves VAPID y el secreto del cron viven en Vault (nunca en el app).
--  * pg_cron llama cada 15 minutos a la funcion angels-push; respaldo
--    diario con make_backup().
-- =====================================================================

create table angels.push_subscriptions (
  id          bigint generated by default as identity primary key,
  player_id   text not null references angels.players(id),
  endpoint    text not null unique,
  p256dh      text not null,
  auth        text not null,
  user_agent  text,
  created_at  timestamptz not null default now(),
  last_ok_at  timestamptz,
  failures    int not null default 0,
  constraint push_endpoint_https check (endpoint like 'https://%' and length(endpoint) <= 1000)
);
create index push_subscriptions_player_idx on angels.push_subscriptions (player_id);

create table angels.reminder_log (
  id            bigint generated by default as identity primary key,
  player_id     text not null references angels.players(id),
  session_date  date not null,
  attempt       smallint not null,
  sent_at       timestamptz not null default now(),
  delivered     int not null default 0,
  constraint reminder_log_once unique (player_id, session_date, attempt)
);

alter table angels.push_subscriptions enable row level security;
alter table angels.reminder_log       enable row level security;
-- El coach solo necesita saber quien tiene avisos activos y que se envio.
create policy push_subscriptions_staff on angels.push_subscriptions for select to authenticated using ((select angels.is_staff()));
create policy reminder_log_staff       on angels.reminder_log       for select to authenticated using ((select angels.is_staff()));
grant select on angels.push_subscriptions, angels.reminder_log to authenticated;
grant all on angels.push_subscriptions, angels.reminder_log to service_role;
grant usage, select on all sequences in schema angels to authenticated, service_role;
revoke all on angels.push_subscriptions, angels.reminder_log from anon;

-- El jugador guarda su suscripcion con su token. Maximo 4 telefonos.
create or replace function angels.player_save_push(p_token text, p_endpoint text, p_p256dh text, p_auth text, p_ua text)
 returns jsonb
 language plpgsql security definer
 set search_path to 'angels', 'pg_temp'
as $function$
declare v_player angels.players%rowtype;
begin
  if p_token is null or length(p_token) < 32 then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  select * into v_player from angels.players where access_token = p_token;
  if not found then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  if p_endpoint is null or p_endpoint not like 'https://%' or length(p_endpoint) > 1000 then
    raise exception 'Suscripcion no valida'; end if;
  if p_p256dh is null or length(p_p256dh) > 200 or p_auth is null or length(p_auth) > 100 then
    raise exception 'Suscripcion no valida'; end if;
  insert into angels.push_subscriptions (player_id, endpoint, p256dh, auth, user_agent)
  values (v_player.id, p_endpoint, p_p256dh, p_auth, left(p_ua, 200))
  on conflict (endpoint) do update
    set player_id = excluded.player_id, p256dh = excluded.p256dh, auth = excluded.auth,
        user_agent = excluded.user_agent, failures = 0;
  return jsonb_build_object('ok', true);
end;
$function$;

-- Hora en que termina la sesion de la categoria ese dia: la del horario de
-- practica; en dia de torneo se toma 7:30pm (aviso a las 8pm).
create or replace function angels.session_end_at(p_team text, p_date date)
 returns timestamp
 language sql stable security definer
 set search_path to 'angels', 'pg_temp'
as $function$
  select p_date + case
    when exists (select 1 from angels.tournaments t where p_team = any(t.teams) and p_date between t.start_date and t.end_date)
      then time '19:30'
    else coalesce((select (s.practice_schedule -> (extract(dow from p_date)::int::text) ->> 'end')::time
                   from angels.team_settings s where s.team = p_team), time '21:00')
  end;
$function$;

create or replace function angels.reminders_due()
 returns table(player_id text, access_token text, session_date date, attempt int, body text)
 language plpgsql stable security definer
 set search_path to 'angels', 'pg_temp'
as $function$
declare
  v_now   timestamp := now() at time zone 'America/Puerto_Rico';
  v_today date := (now() at time zone 'America/Puerto_Rico')::date;
begin
  -- Intento 1: entre 30 minutos y 3 horas despues de terminar la sesion
  -- (cubre una sesion que termine tarde y cruce la medianoche).
  return query
  select p.id, p.access_token, d.dia, 1, 'Te falta el check-in de hoy. Toma menos de un minuto.'::text
  from angels.players p
  cross join (values (v_today), (v_today - 1)) as d(dia)
  where p.status = 'activo'
    and angels.team_has_session(p.team, d.dia)
    and v_now >= angels.session_end_at(p.team, d.dia) + interval '30 minutes'
    and v_now <  angels.session_end_at(p.team, d.dia) + interval '3 hours'
    and not exists (select 1 from angels.entries e where e.player_id = p.id and e.date = d.dia)
    and not exists (select 1 from angels.availability a where a.player_id = p.id and a.date = d.dia and a.status in ('ninguno','lesionado'))
    and not exists (select 1 from angels.reminder_log r where r.player_id = p.id and r.session_date = d.dia and r.attempt = 1)
    and exists (select 1 from angels.push_subscriptions s where s.player_id = p.id);

  -- Intento 2: al dia siguiente entre 6pm y 9pm. Ultimo aviso.
  if v_now::time >= time '18:00' and v_now::time < time '21:00' then
    return query
    select p.id, p.access_token, v_today - 1, 2, 'Te falta el check-in de ayer. Es el último aviso.'::text
    from angels.players p
    where p.status = 'activo'
      and angels.team_has_session(p.team, v_today - 1)
      and not exists (select 1 from angels.entries e where e.player_id = p.id and e.date = v_today - 1)
      and not exists (select 1 from angels.availability a where a.player_id = p.id and a.date = v_today - 1 and a.status in ('ninguno','lesionado'))
      and not exists (select 1 from angels.reminder_log r where r.player_id = p.id and r.session_date = v_today - 1 and r.attempt = 2)
      and exists (select 1 from angels.push_subscriptions s where s.player_id = p.id);
  end if;
end;
$function$;


