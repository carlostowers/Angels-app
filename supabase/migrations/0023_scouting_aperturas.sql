-- =====================================================================
-- ANGELS - 0023 Quién abre el scouting de cada rival
-- ---------------------------------------------------------------------
-- El botón Scouting de la app abre una lista de rivales. Cuando el jugador
-- toca uno, la app registra (jugador, rival, hora) y abre su página en el
-- Playbook de Angels (angelsplay.voleii.com).
-- Solo el staff lee la tabla. El jugador escribe solo por RPC, con su token.
-- =====================================================================

create table angels.scout_opens (
  id         bigint generated by default as identity primary key,
  player_id  text        not null references angels.players(id) on delete cascade,
  rival      text        not null,
  opened_at  timestamptz not null default now(),
  constraint scout_opens_rival_chk check (rival ~ '^[a-z0-9-]{2,40}$')
);
create index scout_opens_rival_player_idx on angels.scout_opens (rival, player_id, opened_at desc);

alter table angels.scout_opens enable row level security;
create policy scout_opens_staff on angels.scout_opens for select to authenticated
  using ((select angels.is_staff()));
revoke all on angels.scout_opens from anon, authenticated;
grant select on angels.scout_opens to authenticated;
grant all on angels.scout_opens to service_role;

-- El jugador abre el scouting de un rival. No repite el registro si abrió
-- el mismo rival en los últimos 2 minutos.
create or replace function angels.player_scout_open(p_token text, p_rival text)
returns jsonb
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_player angels.players%rowtype;
  v_rival  text := lower(btrim(coalesce(p_rival, '')));
begin
  if p_token is null or length(p_token) < 32 then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  select * into v_player from angels.players where access_token = p_token;
  if not found then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  if v_player.status = 'pausado' then
    raise exception 'Tu perfil esta en pausa. Habla con el coach.' using errcode = '28000';
  end if;
  if v_rival !~ '^[a-z0-9-]{2,40}$' then
    raise exception 'Rival no valido';
  end if;
  if exists (select 1 from angels.scout_opens s
             where s.player_id = v_player.id and s.rival = v_rival
               and s.opened_at > now() - interval '2 minutes') then
    return jsonb_build_object('ok', true, 'repetido', true);
  end if;
  insert into angels.scout_opens (player_id, rival) values (v_player.id, v_rival);
  return jsonb_build_object('ok', true);
end;
$$;
revoke all on function angels.player_scout_open(text, text) from public;
grant execute on function angels.player_scout_open(text, text) to anon, authenticated;
