-- =====================================================================
-- 0028 · Uso de la app: historial de entradas y de juegos por jugador
-- ---------------------------------------------------------------------
-- Pedido de Carlos (16 nov. 2026): saber quien entra a la app, quien
-- abre y termina cada juego y cuando, para medir el producto y conocer
-- al equipo. Lo ve solo el staff.
--
-- Que se guarda en angels.app_events (jugador, tipo, referencia, hora):
--   entra       el jugador abrio la app con su enlace (una por cada 30 min)
--   juego_abre  toco la portada de un juego en la app (una por juego cada 2 min)
--   juego_fin   termino una partida: la escribe el servidor al recibir la
--               marca (player_game_submit) o, en asistido, el registro de
--               la partida (player_game_log). El jugador no puede escribirla.
-- No se guarda direccion IP, dispositivo ni ubicacion.
-- El resumen del staff suma tambien las aperturas del scouting (0023).
-- Angels no tiene purga automatica de datos: el historial no se borra solo.
-- Las partidas en linea no se copian: salen de station.bb_rooms y
-- station.bb6_rooms, que ya llevan jugador y hora.
--
-- El jugador solo escribe por RPC con su token. La tabla la lee solo el
-- staff (RLS con angels.is_staff()). El registro de uso nunca puede tumbar
-- una marca ni una partida: angels.uso_registra se traga sus errores.
--
-- Las funciones de juego se reescriben a partir de su definicion vigente
-- (pg_get_functiondef), solo con el cambio de abajo; si un reemplazo no
-- encuentra el texto esperado exactamente una vez, la migracion se detiene.
-- =====================================================================

create table angels.app_events (
  id        bigint generated by default as identity primary key,
  player_id text        not null references angels.players(id) on delete cascade,
  kind      text        not null,
  ref       text,
  meta      jsonb       not null default '{}'::jsonb,
  at        timestamptz not null default now(),
  constraint app_events_kind_chk check (kind = any (array['entra','juego_abre','juego_fin'])),
  constraint app_events_ref_chk  check (ref is null or ref ~ '^[a-z0-9_-]{2,40}$')
);
create index app_events_player_at_idx on angels.app_events (player_id, at desc);
create index app_events_at_idx on angels.app_events (at desc);
comment on table angels.app_events is
  'Historial de uso por jugador: entradas a la app y juegos abiertos y terminados. Solo lo lee el staff.';

alter table angels.app_events enable row level security;
create policy app_events_staff on angels.app_events for select to authenticated
  using ((select angels.is_staff()));
revoke all on angels.app_events from anon, authenticated;
grant select on angels.app_events to authenticated;
grant all on angels.app_events to service_role;

-- Escribe un evento. Uso interno: la llaman las RPC del jugador. Tope de 400
-- eventos por jugador y dia. Cualquier error se descarta.
create or replace function angels.uso_registra(p_player_id text, p_kind text, p_ref text, p_meta jsonb)
returns void
language plpgsql
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_hoy integer;
begin
  select count(*) into v_hoy from angels.app_events
   where player_id = p_player_id and at > now() - interval '1 day';
  if v_hoy >= 400 then
    return;
  end if;
  insert into angels.app_events (player_id, kind, ref, meta)
  values (p_player_id, p_kind, p_ref, coalesce(p_meta, '{}'::jsonb));
exception when others then
  null;
end;
$$;
revoke all on function angels.uso_registra(text, text, text, jsonb) from public, anon, authenticated;

-- El jugador avisa que entro a la app o que abrio un juego.
create or replace function angels.player_event(p_token text, p_kind text, p_ref text default null)
returns jsonb
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_player angels.players%rowtype;
  v_kind   text := lower(btrim(coalesce(p_kind, '')));
  v_ref    text := nullif(lower(btrim(coalesce(p_ref, ''))), '');
begin
  if p_token is null or length(p_token) < 32 then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  select * into v_player from angels.players where access_token = p_token;
  if not found then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  if v_player.status = 'pausado' then
    return jsonb_build_object('ok', false);
  end if;
  if v_kind = 'entra' then
    v_ref := null;
    if exists (select 1 from angels.app_events e
                where e.player_id = v_player.id and e.kind = 'entra'
                  and e.at > now() - interval '30 minutes') then
      return jsonb_build_object('ok', true, 'repetido', true);
    end if;
  elsif v_kind = 'juego_abre' then
    if v_ref is null or v_ref <> all (array['keepup','longspike','bareboru','bareboru6','keepup2']) then
      raise exception 'Juego no valido';
    end if;
    if exists (select 1 from angels.app_events e
                where e.player_id = v_player.id and e.kind = 'juego_abre' and e.ref = v_ref
                  and e.at > now() - interval '2 minutes') then
      return jsonb_build_object('ok', true, 'repetido', true);
    end if;
  else
    raise exception 'Evento no valido';
  end if;
  perform angels.uso_registra(v_player.id, v_kind, v_ref, '{}'::jsonb);
  return jsonb_build_object('ok', true);
end;
$$;
revoke all on function angels.player_event(text, text, text) from public;
grant execute on function angels.player_event(text, text, text) to anon, authenticated;

-- Cada partida terminada deja su evento. Se anade a las funciones vigentes.
do $mig$
declare
  d text;
  n text;
  a text;
begin
  -- 1. La marca (todos los juegos, sin asistido).
  d := pg_get_functiondef('angels.player_game_submit(text,text,integer,jsonb)'::regprocedure);
  if position('uso_registra' in d) > 0 then
    raise notice 'player_game_submit ya registra el uso';
  else
    a := E'\n  return jsonb_build_object(''best'', v_best, ''record'', v_record);\n';
    if (length(d) - length(replace(d, a, ''))) <> length(a) then
      raise exception 'no encontre el final de player_game_submit exactamente una vez';
    end if;
    n := replace(d, a,
      E'\n  perform angels.uso_registra(v_player.id, ''juego_fin'', p_game,\n' ||
      E'    jsonb_strip_nulls(jsonb_build_object(\n' ||
      E'      ''score'', p_score, ''level'', v_level, ''secs'', round(v_secs)::integer,\n' ||
      E'      ''us'',   case when p_game in (''bareboru'', ''bareboru6'') then v_rivals end,\n' ||
      E'      ''them'', case when p_game in (''bareboru'', ''bareboru6'') then v_diff end,\n' ||
      E'      ''record'', v_record)));\n' || a);
    execute n;
  end if;

  -- 2. La partida en asistido (no manda marca): solo bareboru y bareboru6.
  d := pg_get_functiondef('angels.player_game_log(text,text,jsonb)'::regprocedure);
  if position('uso_registra' in d) > 0 then
    raise notice 'player_game_log ya registra el uso';
  else
    a := E'\n  select count(*) into v_hoy from angels.game_plays\n';
    if (length(d) - length(replace(d, a, ''))) <> length(a) then
      raise exception 'no encontre el conteo de player_game_log exactamente una vez';
    end if;
    n := replace(d, a,
      E'\n  if coalesce(p_meta->>''assist'', '''') = ''1'' then\n' ||
      E'    perform angels.uso_registra(v_player.id, ''juego_fin'', p_game,\n' ||
      E'      angels.game_log_clean(coalesce(p_meta, ''{}''::jsonb))\n' ||
      E'        - array[''pa'',''pb'',''pc'',''pd'',''att'',''kill'',''atterr'',''blocked'',''ace'',''blk'',''srverr'',''rallies'',''contacts'',''perf'',''taps'']);\n' ||
      E'  end if;\n' || a);
    execute n;
  end if;
end
$mig$;

-- Partidas en linea de los jugadores de este club, una fila por jugador.
-- Salen de las salas de BAREBORU (esquema station, compartidas por los clubes).
create or replace function angels.uso_linea()
returns table (player_id text, game text, at timestamptz, rival text, us integer, them integer, cerrada boolean, contada boolean)
language sql
stable
set search_path to 'angels', 'pg_temp'
as $$
  select r.host_id, 'bareboru6'::text, coalesce(r.joined_at, r.created_at), r.guest_name,
         case when (r.host_res->>'us') ~ '^[0-9]{1,3}$' then (r.host_res->>'us')::integer end,
         case when (r.host_res->>'them') ~ '^[0-9]{1,3}$' then (r.host_res->>'them')::integer end,
         r.closed_at is not null, coalesce(r.counted, false)
    from station.bb6_rooms r where r.host_club = 'angels' and r.guest_id is not null
  union all
  select r.guest_id, 'bareboru6'::text, coalesce(r.joined_at, r.created_at), r.host_name,
         case when (r.guest_res->>'us') ~ '^[0-9]{1,3}$' then (r.guest_res->>'us')::integer end,
         case when (r.guest_res->>'them') ~ '^[0-9]{1,3}$' then (r.guest_res->>'them')::integer end,
         r.closed_at is not null, coalesce(r.counted, false)
    from station.bb6_rooms r where r.guest_club = 'angels' and r.guest_id is not null
  union all
  select r.host_id, 'bareboru'::text, coalesce(r.joined_at, r.created_at), r.guest_name,
         case when (r.host_res->>'us') ~ '^[0-9]{1,3}$' then (r.host_res->>'us')::integer end,
         case when (r.host_res->>'them') ~ '^[0-9]{1,3}$' then (r.host_res->>'them')::integer end,
         r.closed_at is not null, coalesce(r.counted, false)
    from station.bb_rooms r where r.host_club = 'angels' and r.guest_id is not null
  union all
  select r.guest_id, 'bareboru'::text, coalesce(r.joined_at, r.created_at), r.host_name,
         case when (r.guest_res->>'us') ~ '^[0-9]{1,3}$' then (r.guest_res->>'us')::integer end,
         case when (r.guest_res->>'them') ~ '^[0-9]{1,3}$' then (r.guest_res->>'them')::integer end,
         r.closed_at is not null, coalesce(r.counted, false)
    from station.bb_rooms r where r.guest_club = 'angels' and r.guest_id is not null;
$$;
revoke all on function angels.uso_linea() from public, anon, authenticated;

-- Resumen de uso para el staff: por jugador, por dia, por hora y por juego.
-- Dias y horas en hora de Puerto Rico.
create or replace function angels.staff_uso(p_dias integer default 28)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_dias  integer := least(greatest(coalesce(p_dias, 28), 1), 120);
  v_hoy   date := (now() at time zone 'America/Puerto_Rico')::date;
  v_desde date;
  v_ini   timestamptz;
  v_out   jsonb;
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  v_desde := v_hoy - (v_dias - 1);
  v_ini   := v_desde::timestamp at time zone 'America/Puerto_Rico';

  with act as (
    select e.player_id, e.kind, e.ref as game, e.at from angels.app_events e where e.at >= v_ini
    union all
    select l.player_id, 'linea'::text, l.game, l.at from angels.uso_linea() l where l.at >= v_ini
    union all
    select s.player_id, 'scout'::text, s.rival, s.opened_at from angels.scout_opens s where s.opened_at >= v_ini
  ), actl as (
    select a.player_id, a.kind, a.game, a.at, (a.at at time zone 'America/Puerto_Rico') as loc from act a
  ), jug as (
    select jsonb_build_object(
        'id', p.id,
        'entradas', (select count(*) from actl a where a.player_id = p.id and a.kind = 'entra'),
        'dias', (select count(distinct a.loc::date) from actl a where a.player_id = p.id),
        'ultima', (select max(e.at) from angels.app_events e where e.player_id = p.id and e.kind = 'entra'),
        'ultima_act', (select max(a.at) from actl a where a.player_id = p.id),
        'abre', (select coalesce(jsonb_object_agg(x.game, x.n), '{}'::jsonb)
                   from (select a.game, count(*) as n from actl a
                          where a.player_id = p.id and a.kind = 'juego_abre' group by a.game) x),
        'fin', (select coalesce(jsonb_object_agg(x.game, x.n), '{}'::jsonb)
                  from (select a.game, count(*) as n from actl a
                         where a.player_id = p.id and a.kind = 'juego_fin' group by a.game) x),
        'linea', (select coalesce(jsonb_object_agg(x.game, x.n), '{}'::jsonb)
                    from (select a.game, count(*) as n from actl a
                           where a.player_id = p.id and a.kind = 'linea' group by a.game) x),
        'tot', (select coalesce(jsonb_object_agg(r.game, jsonb_build_object(
                         'plays', r.plays, 'last', r.last_played_at, 'best', r.best_score)), '{}'::jsonb)
                  from angels.game_records r where r.player_id = p.id),
        'linea_tot', (select coalesce(jsonb_object_agg(x.game, x.n), '{}'::jsonb)
                        from (select l.game, count(*) as n from angels.uso_linea() l
                               where l.player_id = p.id group by l.game) x),
        'scout', (select count(*) from actl a where a.player_id = p.id and a.kind = 'scout'),
        'avisos', exists (select 1 from angels.push_subscriptions s where s.player_id = p.id)
      ) as j
    from angels.players p
  )
  select jsonb_build_object(
    'dias', v_dias, 'desde', v_desde, 'hoy', v_hoy,
    'inicio', (select min(e.at) from angels.app_events e),
    'jugadores', (select coalesce(jsonb_agg(jug.j), '[]'::jsonb) from jug),
    'por_dia', (select coalesce(jsonb_agg(jsonb_build_object(
                    'd', d.d::date,
                    'entra', (select count(*) from actl a where a.loc::date = d.d::date and a.kind = 'entra'),
                    'jug',   (select count(distinct a.player_id) from actl a where a.loc::date = d.d::date),
                    'fin',   (select count(*) from actl a where a.loc::date = d.d::date and a.kind = 'juego_fin'),
                    'linea', (select count(*) from actl a where a.loc::date = d.d::date and a.kind = 'linea')
                  ) order by d.d), '[]'::jsonb)
                  from generate_series(v_desde::timestamp, v_hoy::timestamp, interval '1 day') as d(d)),
    'por_hora', (select jsonb_agg(coalesce(h.n, 0) order by g.h)
                   from generate_series(0, 23) as g(h)
                   left join (select extract(hour from a.loc)::integer as h, count(*) as n
                                from actl a group by 1) h on h.h = g.h),
    'juegos', (select coalesce(jsonb_agg(jsonb_build_object(
                    'id', g.id,
                    'abre',  (select count(*) from actl a where a.game = g.id and a.kind = 'juego_abre'),
                    'fin',   (select count(*) from actl a where a.game = g.id and a.kind = 'juego_fin'),
                    'linea', (select count(*) from actl a where a.game = g.id and a.kind = 'linea'),
                    'jug',   (select count(distinct a.player_id) from actl a
                               where a.game = g.id and a.kind in ('juego_abre', 'juego_fin', 'linea')),
                    'tot',   (select coalesce(sum(r.plays), 0) from angels.game_records r where r.game = g.id)
                  ) order by g.ord), '[]'::jsonb)
                 from unnest(array['bareboru6','bareboru','keepup2','longspike','keepup']) with ordinality as g(id, ord))
  ) into v_out;
  return v_out;
end;
$$;
revoke all on function angels.staff_uso(integer) from public, anon;
grant execute on function angels.staff_uso(integer) to authenticated;

-- Historial de un jugador para el staff: lo mas reciente primero.
create or replace function angels.staff_uso_jugador(p_player text, p_limite integer default 300)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_lim integer := least(greatest(coalesce(p_limite, 300), 1), 1000);
  v_out jsonb;
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  if p_player is null or not exists (select 1 from angels.players p where p.id = p_player) then
    raise exception 'Jugador no valido';
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('t', x.at, 'k', x.kind, 'r', x.ref, 'm', x.meta) order by x.at desc), '[]'::jsonb)
    into v_out
    from (
      select u.at, u.kind, u.ref, u.meta from (
        select e.at, e.kind, e.ref, e.meta from angels.app_events e where e.player_id = p_player
        union all
        select l.at, 'linea'::text, l.game,
               jsonb_strip_nulls(jsonb_build_object('rival', l.rival, 'us', l.us, 'them', l.them,
                                                    'cerrada', l.cerrada, 'contada', l.contada))
          from angels.uso_linea() l where l.player_id = p_player
        union all
        select s.opened_at, 'scout'::text, s.rival, '{}'::jsonb from angels.scout_opens s where s.player_id = p_player
      ) u
      order by u.at desc
      limit v_lim
    ) x;
  return jsonb_build_object('eventos', v_out);
end;
$$;
revoke all on function angels.staff_uso_jugador(text, integer) from public, anon;
grant execute on function angels.staff_uso_jugador(text, integer) to authenticated;
