-- =====================================================================
-- ANGELS - 0024 Examen del sistema y del scouting
-- ---------------------------------------------------------------------
-- El examen vive en el Playbook de Angels (angelsplay.voleii.com/#/examen).
-- El jugador lo abre desde el botón Scouting de su app: la app le pasa su
-- token en el hash (#/examen&t=...), que nunca llega a un servidor. Al
-- terminar, el playbook manda sus respuestas por RPC con ese token.
-- La nota se calcula aquí, con la clave guardada en exam_keys: el teléfono
-- no decide la nota. Se guardan todos los intentos.
-- Solo el staff lee las notas. El jugador escribe solo por RPC, con su token.
-- Si cambian las preguntas: nuevo examen (otro id) con su clave, o
-- actualizar la clave de este en exam_keys.
-- =====================================================================

create table angels.exam_keys (
  exam        text        primary key,
  answers     smallint[]  not null,
  updated_at  timestamptz not null default now(),
  constraint exam_keys_exam_chk check (exam ~ '^[a-z0-9-]{2,40}$'),
  constraint exam_keys_len_chk check (coalesce(array_length(answers, 1), 0) between 1 and 200)
);
alter table angels.exam_keys enable row level security;
revoke all on angels.exam_keys from anon, authenticated;
grant all on angels.exam_keys to service_role;

create table angels.exam_results (
  id            bigint generated by default as identity primary key,
  player_id     text        not null references angels.players(id) on delete cascade,
  exam          text        not null references angels.exam_keys(exam) on delete cascade,
  answers       smallint[]  not null,
  score         smallint    not null,
  total         smallint    not null,
  wrong         smallint[]  not null default '{}',
  submitted_at  timestamptz not null default now()
);
create index exam_results_exam_player_idx on angels.exam_results (exam, player_id, submitted_at desc);

alter table angels.exam_results enable row level security;
create policy exam_results_staff on angels.exam_results for select to authenticated
  using ((select angels.is_staff()));
revoke all on angels.exam_results from anon, authenticated;
grant select on angels.exam_results to authenticated;
grant all on angels.exam_results to service_role;

