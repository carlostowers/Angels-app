-- =====================================================================
-- ANGELS - 0012 Mensajes del coach y reinicio de récords de los juegos
-- ---------------------------------------------------------------------
-- 1. Mensajes del coach por Web Push, escritos por Carlos:
--      destino  club (todo Angels), una categoría, un jugador o solo el coach.
--      copia    opcional a los teléfonos del staff.
--      momento  ahora o programado (hasta 30 días). Los programados los
--               envía el cron angels-mensajes, que revisa cada 5 minutos y
--               solo llama a la función cuando hay alguno vencido.
--    Solo llegan a los jugadores activos con los avisos activos. En la app,
--    el jugador ve en Hoy los mensajes de los últimos 7 días.
--    El staff solo lee la tabla; crea y cancela por RPC. Envía angels-push.
-- 2. Reinicio de récords por el coach: un jugador, el coach, una categoría
--    o el club. Pone la marca en cero; no se borran filas.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Mensajes
-- ---------------------------------------------------------------------
create table angels.staff_messages (
  id               bigint generated by default as identity primary key,
  body             text        not null,
  target           text        not null,
  team             text,
  player_id        text        references angels.players(id),
  copy_staff       boolean     not null default false,
  send_at          timestamptz not null default now(),
  status           text        not null default 'programado',
  created_by       text,
  created_at       timestamptz not null default now(),
  claimed_at       timestamptz,
  sent_at          timestamptz,
  targeted         int         not null default 0,
  recipients       int         not null default 0,
  delivered        int         not null default 0,
  staff_delivered  int         not null default 0,
  constraint staff_messages_body_chk   check (length(btrim(body)) between 1 and 240),
  constraint staff_messages_target_chk check (target = any (array['club','team','player','coach'])),
  constraint staff_messages_status_chk check (status = any (array['programado','enviando','enviado','cancelado'])),
  constraint staff_messages_team_chk   check (target <> 'team' or team = any (array['ADCJVBoys'])),
  constraint staff_messages_player_chk check (target <> 'player' or player_id is not null)
);
create index staff_messages_due_idx on angels.staff_messages (send_at) where status = 'programado';
create index staff_messages_sent_idx on angels.staff_messages (sent_at desc) where status = 'enviado';

alter table angels.staff_messages enable row level security;
create policy staff_messages_staff on angels.staff_messages for select to authenticated
  using ((select angels.is_staff()));
revoke all on angels.staff_messages from anon, authenticated;
grant select on angels.staff_messages to authenticated;
grant all on angels.staff_messages to service_role;

-- Crear un mensaje (ahora o programado). p_send_at null = ahora.
create or replace function angels.staff_message_create(p_target text, p_team text, p_player_id text,
                                                        p_body text, p_copy_staff boolean, p_send_at timestamptz)
returns jsonb
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_body  text := btrim(coalesce(p_body, ''));
  v_at    timestamptz := coalesce(p_send_at, now());
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_id    bigint;
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  if length(v_body) < 1 or length(v_body) > 240 then
    raise exception 'El mensaje debe tener entre 1 y 240 caracteres';
  end if;
  if p_target is null or p_target <> all (array['club','team','player','coach']) then
    raise exception 'Destino no valido';
  end if;
  if p_target = 'team' and (p_team is null or p_team <> all (array['ADCJVBoys'])) then
    raise exception 'Categoria no valida';
  end if;
  if p_target = 'player' and not exists (select 1 from angels.players where id = p_player_id and status = 'activo') then
    raise exception 'Ese jugador no esta activo';
  end if;
  if v_at < now() - interval '5 minutes' then
    raise exception 'La hora ya paso';
  end if;
  if v_at > now() + interval '30 days' then
    raise exception 'Solo se puede programar hasta 30 dias';
  end if;
  insert into angels.staff_messages (body, target, team, player_id, copy_staff, send_at, created_by)
  values (v_body, p_target,
          case when p_target = 'team' then p_team end,
          case when p_target = 'player' then p_player_id end,
          case when p_target = 'coach' then false else coalesce(p_copy_staff, false) end,
          greatest(v_at, now()), v_email)
  returning id into v_id;
  return jsonb_build_object('id', v_id, 'inmediato', v_at <= now() + interval '1 minute');
end;
$$;

-- Cancelar un programado que todavía no ha salido.
create or replace function angels.staff_message_cancel(p_id bigint)
returns jsonb
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare v_n int;
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  update angels.staff_messages set status = 'cancelado'
   where id = p_id and status = 'programado';
  get diagnostics v_n = row_count;
  if v_n = 0 then
    raise exception 'Ese mensaje ya salio o ya estaba cancelado';
  end if;
  return jsonb_build_object('ok', true);
end;
$$;

-- Jugadores a los que va un mensaje: activos del destino.
create or replace function angels.message_recipients(p_id bigint)
returns table(player_id text, access_token text)
language sql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
  select p.id, p.access_token
    from angels.staff_messages m
    join angels.players p on p.status = 'activo'
     and (m.target = 'club'
          or (m.target = 'team' and p.team = m.team)
          or (m.target = 'player' and p.id = m.player_id))
   where m.id = p_id;
$$;

-- Tomar un mensaje para enviarlo (envío inmediato). Solo si sigue
-- programado y ya le toca: así nunca sale dos veces.
create or replace function angels.staff_message_claim(p_id bigint)
returns setof angels.staff_messages
language sql
security definer
set search_path to 'angels', 'pg_temp'
as $$
  update angels.staff_messages
     set status = 'enviando', claimed_at = now()
   where id = p_id and status = 'programado' and send_at <= now() + interval '1 minute'
  returning *;
$$;

-- Tomar los programados vencidos (cron). Un envío que quedó a medias más
-- de 15 minutos se cierra como enviado para que no se repita.
create or replace function angels.staff_messages_claim_due()
returns setof angels.staff_messages
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
begin
  update angels.staff_messages
     set status = 'enviado', sent_at = coalesce(sent_at, now())
   where status = 'enviando' and claimed_at < now() - interval '15 minutes';
  return query
  update angels.staff_messages
     set status = 'enviando', claimed_at = now()
   where status = 'programado' and send_at <= now()
  returning *;
end;
$$;

-- Buzón del jugador: lo enviado en los últimos 7 días a su club, su
-- categoría o a él. Nunca los mensajes que el coach se manda solo a sí.
create or replace function angels.player_messages(p_token text)
returns jsonb
language plpgsql
stable
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare v_player angels.players%rowtype;
begin
  if p_token is null or length(p_token) < 32 then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  select * into v_player from angels.players where access_token = p_token;
  if not found then
    raise exception 'Enlace no valido' using errcode = '28000';
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object('id', m.id, 'body', m.body, 'sent_at', m.sent_at) order by m.sent_at desc)
      from (select * from angels.staff_messages m
             where m.status = 'enviado'
               and m.sent_at > now() - interval '7 days'
               and (m.target = 'club'
                    or (m.target = 'team' and m.team = v_player.team)
                    or (m.target = 'player' and m.player_id = v_player.id))
             order by m.sent_at desc limit 20) m
  ), '[]'::jsonb);
end;
$$;

-- ---------------------------------------------------------------------
-- 2. Reinicio de récords
--   p_alcance  'jugador' (p_valor = id), 'coach', 'equipo' (p_valor = ADCJVBoys) o 'club' (todos los jugadores y el coach).
--   p_modo     'todo' o 'marca': en Angels los dos ponen la marca en cero.
-- ---------------------------------------------------------------------
create or replace function angels.staff_game_reset(p_game text, p_alcance text, p_valor text, p_modo text)
returns jsonb
language plpgsql
security definer
set search_path to 'angels', 'pg_temp'
as $$
declare
  v_n int := 0;
  v_c int := 0;
begin
  if not angels.is_staff() then
    raise exception 'Solo staff' using errcode = '28000';
  end if;
  if p_game is null or p_game <> all (array['keepup','longspike']) then
    raise exception 'Juego no valido';
  end if;
  if p_modo is null or p_modo <> all (array['todo','marca']) then
    raise exception 'Modo no valido';
  end if;
  if p_alcance is null or p_alcance <> all (array['jugador','coach','equipo','club']) then
    raise exception 'Alcance no valido';
  end if;
  if p_alcance = 'equipo' and (p_valor is null or p_valor <> all (array['ADCJVBoys'])) then
    raise exception 'Categoria no valida';
  end if;
  if p_alcance = 'jugador' and p_valor is null then
    raise exception 'Falta el jugador';
  end if;

  if p_alcance <> 'coach' then
    -- 'todo' y 'marca' ponen la marca en cero (las filas se quedan).
    update angels.game_records r
       set best_score = 0, best_level = null, best_meta = '{}'::jsonb, best_at = null
     where r.game = p_game
       and (p_alcance = 'club'
            or (p_alcance = 'jugador' and r.player_id = p_valor)
            or (p_alcance = 'equipo' and r.player_id in (select id from angels.players where team = p_valor)));
    get diagnostics v_n = row_count;
  end if;

  if p_alcance in ('coach', 'club') then
    update angels.staff_game_records
       set best_score = 0, best_level = null, best_meta = '{}'::jsonb, best_at = null
     where game = p_game;
    get diagnostics v_c = row_count;
  end if;

  return jsonb_build_object('jugadores', v_n, 'coach', v_c);
end;
$$;

